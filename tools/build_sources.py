#!/usr/bin/env python3
"""Validate source evidence and generate the GitHub source catalogue."""

import argparse
import sys
from urllib.parse import quote

from lib.source_registry import ROOT, edition_order, resolve

OUT = ROOT / "sources" / "SOURCES.md"
GROUPS = {
    "The text and its copies": {"base", "excavated", "transmitted"},
    "Commentaries": {"commentary"},
    "Characters": {"dictionary", "reference"},
    "Context": {"context"},
    "Translations read for range": {"translation"},
}


def link(label, url):
    escaped = label.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")
    return f"[{escaped}](<{url}>)"


def local(path):
    return "../" + quote(path, safe="/#")


def passage(ref):
    label = ref.get("locator", "Passage citation")
    url = ref.get("url")
    return link(label, url if "://" in url else local(url)) if url else label


def render(registry):
    totals = registry.totals
    out = [
        "<!-- Generated by tools/build_sources.py. Do not edit. -->",
        "# Sources",
        "",
        f"The catalogue contains {totals['sources']} sources. "
        f"{totals['stored']} have material in this repository. "
        f"{totals['pending_print']} of {totals['readings']} recorded witness readings await checks in print.",
        "",
        f"Citation recovery is incomplete in {totals['incomplete_entries']} of {totals['entries']} glossary entries. "
        "Glossary links show the citations recorded so far.",
        "",
        "The excavated readings here are individual facts. A qualifying transcription can be "
        "admitted under the [source policy](PROVENANCE.md#excavated).",
        "",
    ]
    for heading, kinds in GROUPS.items():
        out.extend((f"## {heading}", ""))
        records = sorted((r for r in registry.records.values() if r["kind"] in kinds),
                         key=lambda r: (r["kind"] != "base", r.get("years", [9999])[0], r["id"]))
        for source in records:
            ident = source["id"]
            out.extend((f'<a name="{ident}"></a>', f"### {source['name']}", ""))
            details = [source[key] for key in ("date", "found") if key in source]
            if source.get("author_dates"):
                details.append(f"Author dates {source['author_dates']}")
            coverage = source["coverage"]
            if "total" in coverage:
                label = "chapters attested" if source["kind"] == "excavated" else "chapters covered"
                details.append(f"{len(coverage['chapters'])} of {coverage['total']} {label}")
            if "items" in coverage:
                details.append(f"{coverage['items']} dictionary entries in the stored selection")
            if details:
                out.extend((" · ".join(details), ""))
            use = {"stored": "Stored in this repository", "facts": "Recorded as evidence",
                   "consulted": "Consulted for context"}[source["use"]]
            if ident == "base":
                use += ". The listed printings are independent witnesses for comparison"
            if source["chain"]:
                use += " · via " + " → ".join(link(registry.records[x]["name"], f"#{x}")
                                              for x in source["chain"])
            out.extend((use + ".", ""))
            if source.get("pending_print"):
                out.extend((f"{source['pending_print']} readings await a print check.", ""))
            if source.get("pending_via"):
                out.extend((f"{source['pending_via']} readings acquired here await a print check.", ""))
            if source.get("confirmed_print"):
                out.extend((f"{source['confirmed_print']} readings have been checked in print.", ""))
            if source.get("citation_debt"):
                out.extend((f"Citation recovery is open in [{source['citation_debt']}](../WORKLIST.md).", ""))
            for edition in sorted(registry.editions[ident].values(), key=edition_order):
                title = link(edition["title"], edition["url"]) if "url" in edition else edition["title"]
                detail = [str(edition[key]) for key in ("publisher", "year", "date") if edition.get(key)]
                suffix = (" · " + " · ".join(detail)) if detail else ""
                out.append(f"- {title}{suffix}")
            if "url" in source and not any(e.get("url") == source["url"]
                                          for e in registry.editions[ident].values()):
                out.append("- " + link("Source online", source["url"]))
            if source.get("scan"):
                out.append("- " + link("Scan", source["scan"]))
            for path in source["holds"]:
                out.append("- " + link("Recorded inventory" if source["kind"] == "excavated"
                                      else "Stored material", local(path)))
            for slug in source["entries"]:
                for ref in registry.entries[slug]["refs"]:
                    if ref["source"] != ident:
                        continue
                    anchor = f"#{ref['at']}" if ref.get("at") else ""
                    term = slug.split("-")
                    entry_label = "-".join(part for part in term if part.isascii()) or "entry"
                    out.append("- " + link(f"Glossary · {entry_label}", local(f"glossary/{slug}.md{anchor}"))
                               + " · " + passage(ref))
            for fork_id in source["forks"]:
                fork = registry.forks[fork_id]
                for ref in fork["refs"]:
                    if ref["source"] == ident:
                        out.append(f"- Chapter {fork['chapter']} evidence · " + passage(ref))
            if source["chapters"]:
                out.append("- Apparatus chapters " + ", ".join(
                    link(str(n), local(f"chapters/{n:03}.md")) for n in source["chapters"])
                    + " · " + link("manuscript decisions", "../notes/manuscript.md"))
            out.extend(("- " + link("Admission policy", local(source["policy"])), ""))
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate without writing")
    args = parser.parse_args()
    try:
        expected = render(resolve())
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != expected:
            print("sources/SOURCES.md is stale. Run python3 tools/build_sources.py", file=sys.stderr)
            return 1
    else:
        OUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
